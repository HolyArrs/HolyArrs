WEB = ROOT / "app" / "frontend"
DIST = ROOT / "app" / "frontend" / "dist"
TABLE_START = "<!-- notices: generated by deploy/release/notices.py; do not edit by hand -->"
FONT = re.compile(r"(?i)\.(woff2?|ttf|otf|eot)$")
LICENCE_FILE = re.compile(r"(?i)^(licen[cs]e|copying|notice|patents|unlicense)([.\-_].*)?$")
# The video tool ships as one release program with one row; its bundled parts are never listed.
SKIPPED = re.compile(r"(?i)yt-dlp.*(bundled|third[-_ ]?party|credit)|third_party_licenses")
# A file that gathers the licences of several parts: every licence in it counts.
GATHERED = re.compile(r"(?i)(3rd|third)[-_ ]?party")

