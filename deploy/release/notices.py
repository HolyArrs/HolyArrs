#!/usr/bin/env python3
"""Third-party notices: every part HolyArrs ships, with its licence.

Writes docs/third-party-notices.md (each part with its licence files) and
the "Open-source parts" table at the end of THIRD_PARTY_NOTICES.md from:

- the Go modules `go list -deps ./app/backend/cmd/holyarrs` links, for every release
  target in deploy/release/package.py (they differ per system), with the licence
  files from each linked package's folder up to its module's root;
- the npm packages the built app holds (app/frontend/bundled-packages.json,
  written by the app's build), with their licence files, plus hls.js,
  which the build copies beside the app;
- the third-party files in app/frontend/static (app/frontend/static-parts.json),
  which the build copies as they are;
- the few other parts below (Go itself and the Docker image's CA list).

    python deploy/release/notices.py          write both files
    python deploy/release/notices.py --check  fail when a shipped part is missing,
                                       stale or of another version

The check needs Go and its module cache, not app/frontend/node_modules.
"""
